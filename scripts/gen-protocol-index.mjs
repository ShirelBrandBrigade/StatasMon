// Builds packages/protocol/generated/index.ts from the ts-rs output.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "packages", "protocol", "generated");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();
const body = files
  .map((f) => `export type { ${f.replace(/\.ts$/, "")} } from "./${f.replace(/\.ts$/, "")}";`)
  .join("\n");
writeFileSync(
  join(dir, "index.ts"),
  `// Generated by scripts/gen-protocol-index.mjs — do not edit.\n${body}\n`,
);
console.log(`protocol index: ${files.length} types`);
